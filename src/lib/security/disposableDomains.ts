/**
 * Extracts and normalizes the domain portion of an email address.
 */
export function extractEmailDomain(email: string): string | null {
	const trimmed = email.trim().toLowerCase();
	const atIndex = trimmed.lastIndexOf("@");
	if (atIndex <= 0 || atIndex === trimmed.length - 1) {
		return null;
	}
	const domain = trimmed.slice(atIndex + 1).replace(/\.+$/, "");
	return domain || null;
}

/**
 * Reads optional comma-separated extra blocked domains from environment config.
 */
function getExtraBlockedDomains(): string[] {
	const raw =
		typeof process !== "undefined" ? process.env?.EXTRA_BLOCKED_EMAIL_DOMAINS : undefined;
	if (!raw) return [];
	return raw
		.split(",")
		.map((d) => d.trim().toLowerCase().replace(/^@/, ""))
		.filter(Boolean);
}

/**
 * Checks whether an email address belongs to a known disposable/temporary email domain
 * (including any subdomains of a blocked domain) or an env-configured blocked domain.
 */
export function isDisposableEmail(email: string): boolean {
	const domain = extractEmailDomain(email);
	if (!domain) return false;

	if (DISPOSABLE_EMAIL_DOMAINS.has(domain)) {
		return true;
	}

	// Check parent domains for subdomain throwaway addresses (e.g. sub.mailinator.com)
	const parts = domain.split(".");
	for (let i = 1; i < parts.length - 1; i++) {
		const parent = parts.slice(i).join(".");
		if (DISPOSABLE_EMAIL_DOMAINS.has(parent)) {
			return true;
		}
	}

	const extraDomains = getExtraBlockedDomains();
	if (extraDomains.length > 0) {
		for (const blocked of extraDomains) {
			if (domain === blocked || domain.endsWith(`.${blocked}`)) {
				return true;
			}
		}
	}

	return false;
}
